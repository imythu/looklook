const DETAIL_ZH = { thinking: '思考中' };

/**
 * 拆成主文字和补充说明；时间去掉（界面自己计时）。
 * 换成中文时 `orig` 是原来的英文动词（界面上跟在后面小字显示），没换时为空。
 * @returns {{ text: string, detail: string, orig: string }}
 */
export function spinnerText(activity, lang) {
  const s = (activity ?? '').trim();
  const m = s.match(/^(.*?…)\s*(?:\((.*)\))?$/);
  if (!m) return { text: s, detail: '', orig: '' };
  const zh = /^zh/i.test(lang ?? '');
  let text = m[1];
  let orig = '';
  const verb = text.slice(0, -1).trim();
  if (zh && Object.hasOwn(SPINNER_ZH, verb)) {
    text = `${SPINNER_ZH[verb]}…`;
    orig = verb;
  }
  const detail = (m[2] ?? '')
    .split('·')
    .map((x) => x.trim())
    .filter((x) => x && !/^\d+[hms](\s*\d+[ms])*$/.test(x))
    .map((x) => (zh ? DETAIL_ZH[x] ?? x.replace(/^thought for (.+)$/, '想了 $1') : x))
    .join(' · ');
  return { text, detail, orig };
}
